import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const catalog = JSON.parse(
  await readFile(new URL("src/resources/catalog.json", root), "utf8"),
);
const identifier = /^[A-Za-z_$][\w$]*$/;
const capitalize = (value) => value[0].toUpperCase() + value.slice(1);
function flatten(value, prefix = "") {
  return Object.entries(value).flatMap(([key, item]) => {
    const name = prefix ? prefix + capitalize(key) : key;
    if (!identifier.test(name))
      throw new Error(`Invalid resource identifier: ${name}`);
    if (typeof item === "string") return [[name, item]];
    if (!item || typeof item !== "object" || Array.isArray(item))
      throw new Error(`Invalid string resource: ${name}`);
    return flatten(item, name);
  });
}
const locales = Object.keys(catalog.locales);
if (!locales.length) throw new Error("At least one locale is required.");
const localized = Object.fromEntries(
  locales.map((locale) => [
    locale,
    Object.fromEntries(flatten(catalog.locales[locale])),
  ]),
);
const keys = Object.keys(localized[locales[0]]);
for (const locale of locales) {
  if (
    Object.keys(localized[locale]).sort().join("\n") !==
    [...keys].sort().join("\n")
  ) {
    throw new Error(`String keys do not match in locale ${locale}`);
  }
}
const imports = [];
const resources = {};
const pagefindKeys = {
  placeholder: "pagefindPlaceholder",
  clear_search: "pagefindClearSearch",
  load_more: "pagefindLoadMore",
  search_label: "pagefindSearchLabel",
  filters_label: "pagefindFiltersLabel",
  zero_results: "pagefindZeroResults",
  many_results: "pagefindManyResults",
  one_result: "pagefindOneResult",
  total_zero_results: "pagefindTotalZeroResults",
  total_one_result: "pagefindTotalOneResult",
  total_many_results: "pagefindTotalManyResults",
  alt_search: "pagefindAltSearch",
  search_suggestion: "pagefindSearchSuggestion",
  searching: "pagefindSearching",
  results_label: "pagefindResultsLabel",
  keyboard_navigate: "pagefindKeyboardNavigate",
  keyboard_select: "pagefindKeyboardSelect",
  keyboard_clear: "pagefindKeyboardClear",
  keyboard_close: "pagefindKeyboardClose",
};
for (const category of ["images", "vectors", "fonts", "assets"]) {
  resources[category] = Object.entries(catalog[category] ?? {})
    .map(([key, item]) => {
      if (!identifier.test(key))
        throw new Error(`Invalid ${category} resource identifier: ${key}`);
      if (typeof item === "string")
        return `    ${key}: ${JSON.stringify(item)},`;
      if (typeof item.import !== "string")
        throw new Error(`Missing import for ${category}.${key}`);
      const variable = `${category}_${key}`;
      imports.push(`import ${variable} from ${JSON.stringify(item.import)};`);
      return `    ${key}: ${variable},`;
    })
    .join("\n");
}
const output = `// Generated by scripts/generate-resources.mjs. Edit catalog.json, then run npm run resources.\n${imports.join("\n")}\n\nexport const translations = ${JSON.stringify(catalog.locales, null, 2)} as const;\n\nconst strings = ${JSON.stringify(localized, null, 2)} as const;\nexport type ResourceLocale = keyof typeof strings;\n\nfunction getStrings(locale: string) {\n  if (!Object.prototype.hasOwnProperty.call(strings, locale)) {\n    throw new Error(\x60Unsupported resource locale: \x24{locale}\x60);\n  }\n  return strings[locale as ResourceLocale];\n}\n\nexport const res = {\n  pagefindTranslations: (locale: string = ${JSON.stringify(locales[0])}) => ({\n${Object.entries(
  pagefindKeys,
)
  .map(([key, value]) => `    ${key}: getStrings(locale).${value},`)
  .join(
    "\n",
  )}\n  }),\n  str: {\n${keys.map((key) => `    ${key}: (locale: string = ${JSON.stringify(locales[0])}): string => getStrings(locale).${key},`).join("\n")}\n  },\n${Object.entries(
  resources,
)
  .map(([category, entries]) => `  ${category}: {\n${entries}\n  },`)
  .join("\n")}\n} as const;\n`;
await writeFile(new URL("src/resources/generated.ts", root), output);
const paths = Object.fromEntries(
  ["images", "vectors", "fonts", "assets"].map((category) => [
    category,
    Object.fromEntries(
      Object.entries(catalog[category] ?? {}).filter(
        ([, value]) => typeof value === "string",
      ),
    ),
  ]),
);
await writeFile(
  new URL("src/resources/paths.ts", root),
  `// Generated by scripts/generate-resources.mjs. Safe to import from Astro configuration.\nexport const res = ${JSON.stringify(paths, null, 2)} as const;\n`,
);

console.log(
  `Generated ${keys.length} strings in ${locales.length} locale(s), plus bundled resource constants.`,
);
